-- Phase 4.6: Messaging and Inquiries

-- 1. Helper trigger function for updated_at if not already present
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 2. Create inquiries table
CREATE TABLE IF NOT EXISTS inquiries (
    inquiry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id UUID REFERENCES profiles(id) NOT NULL,
    pharmacy_id BIGINT REFERENCES pharmacies(pharmacy_id) NOT NULL,
    item_id BIGINT REFERENCES master_catalog(item_id), -- Nullable for general inquiries, present for Rx inquiries
    subject TEXT NOT NULL DEFAULT 'Prescription Stock Inquiry',
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Update messages table
ALTER TABLE messages ALTER COLUMN order_id DROP NOT NULL;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS inquiry_id BIGINT REFERENCES inquiries(inquiry_id) ON DELETE CASCADE;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_message_target'
    ) THEN
        ALTER TABLE messages ADD CONSTRAINT chk_message_target CHECK (
            (order_id IS NOT NULL AND inquiry_id IS NULL) OR 
            (order_id IS NULL AND inquiry_id IS NOT NULL)
        );
    END IF;
END $$;

-- 4. Add Indexes for performance
CREATE INDEX IF NOT EXISTS idx_messages_inquiry_id ON messages(inquiry_id);
CREATE INDEX IF NOT EXISTS idx_inquiries_customer_id ON inquiries(customer_id);
CREATE INDEX IF NOT EXISTS idx_inquiries_pharmacy_id ON inquiries(pharmacy_id);

-- 5. RLS for Inquiries
ALTER TABLE inquiries ENABLE ROW LEVEL SECURITY;

-- Customers can read their own inquiries
DROP POLICY IF EXISTS "Customers can view their own inquiries" ON inquiries;
CREATE POLICY "Customers can view their own inquiries"
    ON inquiries FOR SELECT
    USING (auth.uid() = customer_id);

-- Customers can create their own inquiries
DROP POLICY IF EXISTS "Customers can create their own inquiries" ON inquiries;
CREATE POLICY "Customers can create their own inquiries"
    ON inquiries FOR INSERT
    WITH CHECK (auth.uid() = customer_id);

-- Staff can view inquiries for their pharmacy
DROP POLICY IF EXISTS "Staff can view inquiries for their pharmacy" ON inquiries;
CREATE POLICY "Staff can view inquiries for their pharmacy"
    ON inquiries FOR SELECT
    USING (
        pharmacy_id IN (SELECT pharmacy_id FROM pharmacy_staff WHERE staff_id = auth.uid())
    );

-- Staff can update inquiries for their pharmacy (e.g., closing them)
DROP POLICY IF EXISTS "Staff can update inquiries for their pharmacy" ON inquiries;
CREATE POLICY "Staff can update inquiries for their pharmacy"
    ON inquiries FOR UPDATE
    USING (
        pharmacy_id IN (SELECT pharmacy_id FROM pharmacy_staff WHERE staff_id = auth.uid())
    );

-- Admins can do anything on inquiries
DROP POLICY IF EXISTS "Admins have full access to inquiries" ON inquiries;
CREATE POLICY "Admins have full access to inquiries"
    ON inquiries FOR ALL
    USING (
        EXISTS (
            SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin'
        )
    );

-- 6. RLS for Messages on inquiries
DROP POLICY IF EXISTS "Customers can insert messages on their inquiries" ON messages;
CREATE POLICY "Customers can insert messages on their inquiries"
    ON messages FOR INSERT
    WITH CHECK (
        auth.uid() = sender_id AND
        EXISTS (
            SELECT 1 FROM inquiries WHERE inquiry_id = messages.inquiry_id AND customer_id = auth.uid()
        )
    );

DROP POLICY IF EXISTS "Customers can read messages on their inquiries" ON messages;
CREATE POLICY "Customers can read messages on their inquiries"
    ON messages FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM inquiries WHERE inquiry_id = messages.inquiry_id AND customer_id = auth.uid()
        )
    );

DROP POLICY IF EXISTS "Staff can insert messages on their pharmacy inquiries" ON messages;
CREATE POLICY "Staff can insert messages on their pharmacy inquiries"
    ON messages FOR INSERT
    WITH CHECK (
        auth.uid() = sender_id AND
        EXISTS (
            SELECT 1 FROM inquiries i
            JOIN pharmacy_staff ps ON ps.pharmacy_id = i.pharmacy_id
            WHERE i.inquiry_id = messages.inquiry_id AND ps.staff_id = auth.uid()
        )
    );

DROP POLICY IF EXISTS "Staff can read messages on their pharmacy inquiries" ON messages;
CREATE POLICY "Staff can read messages on their pharmacy inquiries"
    ON messages FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM inquiries i
            JOIN pharmacy_staff ps ON ps.pharmacy_id = i.pharmacy_id
            WHERE i.inquiry_id = messages.inquiry_id AND ps.staff_id = auth.uid()
        )
    );

-- 7. Update realtime publication to include inquiries
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND tablename = 'inquiries'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE inquiries;
    END IF;
EXCEPTION WHEN OTHERS THEN
    NULL;
END $$;

-- 8. Trigger for updated_at
DROP TRIGGER IF EXISTS set_inquiries_updated_at ON inquiries;
CREATE TRIGGER set_inquiries_updated_at
BEFORE UPDATE ON inquiries
FOR EACH ROW
EXECUTE FUNCTION public.handle_updated_at();
